const buildPosition = (
  shares: number,
  avgCost: number,
  currentPrice: number,
  dayChangePercent: number,
) => {
  const marketValue = Number((shares * currentPrice).toFixed(2));
  const dayGainLoss = Number((marketValue * (dayChangePercent / 100)).toFixed(2));
  const totalGainLoss = Number(((currentPrice - avgCost) * shares).toFixed(2));
  const totalGainLossPercent = Number(
    (((currentPrice - avgCost) / avgCost) * 100).toFixed(1),
  );

  return {
    shares,
    avgCost,
    marketValue,
    dayGainLoss,
    dayGainLossPercent: dayChangePercent,
    totalGainLoss,
    totalGainLossPercent,
    currency: "USD" as const,
  };
};

